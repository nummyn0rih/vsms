// Оттенки категорий калибра — ОДИН источник для большого стека (CalibreStack) и мини-стека
// в таблице поставщиков (SupplierTable). Новых цветов не вводим: принятые категории — оттенки
// цвета культуры, «не в зачёт» и брак — штриховка янтарём (класс .reject в CSS).

// Чем дальше категория по списку принятых, тем светлее — структура партии читается одной
// полосой. Ниже 30% не осветляем, иначе ломоть сливается с фоном.
export function shade(color: string, index: number): string {
  const mix = Math.max(30, 100 - index * 26);
  return `color-mix(in srgb, ${color} ${mix}%, #ffffff)`;
}
